const dicts: Record<Locale, Record<Key, string>> = { it, en }

export type T = (key: Key, vars?: Record<string, string | number>) => string

interface I18n {
  locale: Locale
  t: T
  setLocale: (l: '' | Locale) => void
  /** Human-readable message for an error from the API. */
  errorText: (e: unknown) => string
}

const Ctx = createContext<I18n | null>(null)

export function browserLocale(): Locale {
  return navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en'
}

export function I18nProvider({ initial, children }: { initial: '' | Locale; children: ReactNode }) {
  const [pref, setPref] = useState<'' | Locale>(initial)
  const locale: Locale = pref || browserLocale()
  const value = useMemo<I18n>(() => {
    const d = dicts[locale]
    const t: T = (key, vars) => {
      let s = d[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
      return s
    }
    const errorText = (e: unknown) => {
      if (e instanceof ApiError) {
        const k = `err.${e.code}` as Key
        return k in d ? d[k] : e.message
      }
      return e instanceof Error ? e.message : String(e)
    }
    document.documentElement.lang = locale
    return { locale, t, setLocale: setPref, errorText }
  }, [locale])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const c = useContext(Ctx)
  if (!c) throw new Error('I18nProvider missing')
  return c
}
